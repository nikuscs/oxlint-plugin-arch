import { describe, it } from 'vitest'
import { testerRun } from '../../utils/tester.utils.ts'
import { typesNamespaceImport } from './types-namespace-import.ts'

describe('arch/types-namespace-import', () => {
  it.each([
    { name: 'three type imports pass', code: "import type { User, Role, Team } from './user.types'" },
    { name: 'value imports pass', code: "import { User, Role, Team, Invite } from './user'" },
    { name: 'one value import keeps the list', code: "import { User, type Role, type Team, type Invite, type Seat } from './user'" },
    { name: 'a default import keeps the list', code: "import User, { type Role, type Team, type Invite, type Seat } from './user'" },
    { name: 'a namespace import passes', code: "import type * as UserTypes from './user.types'" },
    { name: 'a default type import passes', code: "import type User from './user.types'" },
    { name: 'a side-effect import passes', code: "import './user.css'" },
    { name: 'custom max', code: "import type { User, Role, Team, Invite } from './user.types'", options: { max: 4 } },
    { name: 'a list of three package types passes', code: 'import type { A, B, C } from "x"' },
    { name: 'a list of three inline type specifiers passes', code: 'import { type A, type B, type C } from "x"' },
    { name: 'a list of four package values passes', code: 'import { A, B, C, D } from "x"' },
    { name: 'a mixed package import passes', code: 'import { A, type B, type C, type D, type E } from "x"' },
    { name: 'a default import beside four types passes', code: 'import Default, { type A, type B, type C, type D } from "x"' },
    { name: 'a package namespace type import passes', code: 'import type * as X from "x"' },
    { name: 'a package default type import passes', code: 'import type Default from "x"' },
    { name: 'a package side-effect import passes', code: 'import "x"' },
    { name: 'a type list at the custom maximum passes', code: 'import type { A, B, C, D } from "./room.types";', options: { max: 4 } },
    { name: 'an empty type import at zero maximum passes', code: 'import type {} from "x"', options: { max: 0 } },
    {
      name: 'a tuple of namespace references passes',
      code: 'import type * as RoomTypes from "./room.types";\nexport type Result = [RoomTypes.A, RoomTypes.B, RoomTypes.C, RoomTypes.D]',
    },
    {
      name: 'a JSX element using namespace references passes',
      code: 'import type * as RoomTypes from "./room.types";\nconst view = <Widget<RoomTypes.A> value={null as RoomTypes.B} />',
    },
    { name: 'four type imports', code: "import type { User, Role, Team, Invite } from './user.types'", errors: ['namespace'] },
    { name: 'inline type specifiers', code: "import { type User, type Role, type Team, type Invite } from './user'", errors: ['namespace'] },
    { name: 'each import reports', code: "import type { A, B, C, D } from './a'\nimport type { E, F, G, H } from './e'", errors: ['namespace', 'namespace'] },
    { name: 'max 0', code: "import type { User } from './user.types'", options: { max: 0 }, errors: ['namespace'] },
    {
      name: 'custom name',
      code: "import type { User, Role } from '@app/user'",
      options: { max: 1, names: { '@app/user': 'UserTypes' } },
      errors: ['namespace'],
    },
    { name: 'four named room types', code: 'import type { A, B, C, D } from "./room.types";', errors: ['namespace'] },
    {
      name: 'four types inside an ambient module',
      code: 'declare module "ambient" { import type { A, B, C, D } from "./room.types"; export type T = A }',
      errors: ['namespace'],
    },
    {
      name: 'four types surrounded by CRLF comments',
      code: '// keep before\r\nimport type { A, B, C, D } from "./room.types"; // keep after\r\ntype T = A',
      errors: ['namespace'],
    },
    {
      name: 'four types with import attributes',
      code: 'import type { A, B, C, D } from "x" with { "resolution-mode": "import" }; type T = A',
      errors: ['namespace'],
    },
    {
      name: 'four types used in an exported tuple',
      code: 'import type { A, B, C, D } from "./room.types";\nexport type Result = [A, B, C, D]',
      errors: ['namespace'],
    },
    {
      name: 'two types above a custom maximum and name',
      code: 'import type { A, B } from "x"; type T = A | B',
      options: { max: 1, names: { x: 'Custom' } },
      errors: ['namespace'],
    },
    { name: 'a referenced type above zero maximum', code: 'import type { A } from "x"; type T = A', options: { max: 0 }, errors: ['namespace'] },
    { name: 'four types from a path alias', code: "import type { A, B, C, D } from '#/types/room.types'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a harness module', code: "import type { A, B, C, D } from './harness.types'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a scoped package subpath', code: "import type { A, B, C, D } from '@orbs/server/client'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a types extension', code: "import type { A, B, C, D } from './harness.types.ts'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a declaration extension', code: "import type { A, B, C, D } from './harness.d.ts'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a hyphenated TSX module', code: "import type { A, B, C, D } from './foo-bar.tsx'\ntype T = A", errors: ['namespace'] },
    { name: 'four types from a numeric module name', code: "import type { A, B, C, D } from './123.ts'\ntype T = A", errors: ['namespace'] },
    {
      name: 'four inline type specifiers used in a tuple',
      code: 'import { type A, type B, type C, type D } from "x"; type T = [A, B, C, D]',
      errors: ['namespace'],
    },
    { name: 'an aliased inline type specifier', code: 'import { type A as Local, type B, type C, type D } from "x"; type T = Local<B>', errors: ['namespace'] },
    { name: 'an aliased named type specifier', code: 'import type { A as Local, B, C, D } from "x"; type T = Local<B>', errors: ['namespace'] },
    {
      name: 'imported types in generic and qualified references',
      code: 'import type { A, B, C, D } from "./room.types";\ntype T<U extends A = B> = [C<U>, ReturnType<typeof D>, A["id"], typeof D.member, A.Nested]',
      errors: ['namespace'],
    },
    {
      name: 'imported types in extends and implements clauses',
      code: 'import type { A, B, C, D } from "./room.types";\ninterface T extends A, B.Inner<C> {}\nclass Impl implements D {}',
      errors: ['namespace'],
    },
    {
      name: 'imported names shadowed by local bindings',
      code: 'import type { A, B, C, D } from "./room.types";\ntype T<A> = [A, B]; function f(B: string): C { return {} as C }',
      errors: ['namespace'],
    },
    {
      name: 'imported names repeated in keys and comments',
      code: 'import type { A, B, C, D } from "./room.types";\n// keep A\ntype T = { A: A; B: B }; type U = "C"',
      errors: ['namespace'],
    },
    {
      name: 'an imported name also reexported from elsewhere',
      code: 'import type { A, B, C, D } from "./room.types";\nexport type { A } from "other"; export type T = A',
      errors: ['namespace'],
    },
    {
      name: 'two oversized imports from distinct modules',
      code: 'import type { A, B, C, D } from "./room.types";\nimport type { E, F, G, H } from "other";\ntype T = [A, E]',
      errors: ['namespace', 'namespace'],
    },
    {
      name: 'a namespace name colliding with a value',
      code: 'import type { A, B, C, D } from "./room.types";\nconst RoomTypes = 1;',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'a namespace name colliding with a type',
      code: 'import type { A, B, C, D } from "./room.types";\ntype RoomTypes = string;',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'a namespace name shadowed by a type parameter',
      code: 'import type { A, B, C, D } from "./room.types";\nfunction f<RoomTypes>(value: A): RoomTypes { throw 1 }',
      errors: ['namespace'],
    },
    {
      name: 'a namespace name shadowed inside a function',
      code: 'import type { A, B, C, D } from "./room.types";\nfunction f() { const RoomTypes = 1; return null as A }',
      errors: ['namespace'],
    },
    {
      name: 'a namespace name already used globally',
      code: 'import type { A, B, C, D } from "./room.types";\ntype T = RoomTypes.Global;',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an existing type namespace beside named types',
      code: 'import type { A, B, C, D } from "./room.types";\nimport type * as Existing from "./room.types";',
      errors: ['namespace'],
    },
    {
      name: 'an existing value namespace beside named types',
      code: 'import type { A, B, C, D } from "./room.types";\nimport * as Existing from "./room.types";',
      errors: ['namespace'],
    },
    {
      name: 'an imported type exported by name',
      code: 'import type { A, B, C, D } from "./room.types";\nexport type { A };',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an imported type exported under an alias',
      code: 'import type { A, B, C, D } from "./room.types";\nexport type { A as Public };',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an imported type exported with an inline modifier',
      code: 'import type { A, B, C, D } from "./room.types";\nexport { type A };',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an imported type exported as a value',
      code: 'import type { A, B, C, D } from "./room.types";\nexport { A };',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an imported type referenced as a value',
      code: 'import type { A, B, C, D } from "./room.types";\nconst value = A;',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'an imported type used in an import equals alias',
      code: 'import type { A, B, C, D } from "./room.types";\nimport Alias = A.Member;',
      output: null,
      errors: ['namespace'],
    },
    {
      name: 'a comment between named type specifiers',
      code: 'import type { A, /* keep */ B, C, D } from "x"; type T = A',
      output: null,
      errors: ['namespace'],
    },
    { name: 'a comment before the import source', code: 'import type { A, B, C, D } /* keep */ from "x";', output: null, errors: ['namespace'] },
    { name: 'a nonidentifier string import name', code: 'import type { "a-b" as A, B, C, D } from "x"; type T = A', output: null, errors: ['namespace'] },
    { name: 'an identifier string import name', code: 'import type { "A" as Local, B, C, D } from "x"; type T = Local', errors: ['namespace'] },
    {
      name: 'a reserved word as the configured namespace',
      code: 'import type { A, B, C, D } from "./room.types";',
      options: { names: { './room.types': 'class' } },
      errors: ['namespace'],
    },
    {
      name: 'two oversized imports with matching basenames',
      code: 'import type { A, B, C, D } from "./room.types";\nimport type { E, F, G, H } from "other/room.types";',
      errors: ['namespace', 'namespace'],
    },
    {
      name: 'two oversized imports from the same module',
      code: 'import type { A, B, C, D } from "./room.types";\nimport type { E, F, G, H } from "./room.types";',
      errors: ['namespace', 'namespace'],
    },
    {
      name: 'named imported types used in JSX',
      code: 'import type { A, B, C, D } from "./room.types";\nconst view = <Widget<A> value={null as B} />',
      errors: ['namespace'],
    },
  ])('$name', (row) => testerRun(typesNamespaceImport, row))
})
