import { describe, expect, it } from 'vitest'
import { recipes } from '../../src/preset/preset.ts'
import { testerPreset } from '../utils/tester.utils.ts'
import type { TesterPresetRow } from '../types/tester.types.ts'

describe('preset Effect server', () => {
  const manifest = (name: string, dependencies: Record<string, string>) => JSON.stringify({ name, dependencies })
  const workspaces = JSON.stringify({ workspaces: ['apps/*', 'packages/*'] })
  const tree = ['apps/server/src/domains/order/', 'apps/server/src/rpc/app/', 'apps/server/src/mails/']

  const server = {
    'package.json': workspaces,
    'apps/server/package.json': manifest('server', { effect: '1', kysely: '1' }),
    'apps/server/src/application/app.ts': '',
    'apps/server/src/application/app.config.ts': '',
  }

  const names = '*.constants.ts, *.test.ts, *.spec.ts, *.actions.ts, *.queries.ts, *.layer.ts, *.workflows.ts, *.prompts.ts, *-*.driver.ts'
  const reads = 'A queries file only reads; write in an actions file.'

  it.each<TesterPresetRow>([
    {
      name: 'an Effect workspace with a backend package gets the effect group',
      tree: ['apps/server/src/rpc/'],
      files: server,
      folders: {},
      file: 'apps/server/src/a.ts',
      rule: 'arch/code-traced',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'an Effect workspace with a backend package gets the backend group',
      tree: ['apps/server/src/rpc/'],
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: 'error',
    },
    {
      name: 'an Effect workspace with domains gets the backend group',
      tree: ['apps/server/src/domains/order/', 'apps/server/src/rpc/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', { effect: '1' }) },
      folders: {},
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: 'error',
    },
    {
      name: 'a folder set to the Effect recipe with domains is a server',
      tree: ['apps/server/src/domains/order/', 'apps/server/src/rpc/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', {}) },
      folders: { 'apps/server': recipes.effect },
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: 'error',
    },
    {
      name: 'a folder set to the Effect recipe with domains checks LIKE values in domains',
      tree: ['apps/server/src/domains/order/', 'apps/server/src/rpc/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', {}) },
      folders: { 'apps/server': recipes.effect },
      file: 'apps/server/src/domains/order/order.queries.ts',
      rule: 'arch/backend-sql-like',
      expected: 'error',
    },
    {
      name: 'backend false on an Effect server wins',
      tree: ['apps/server/src/domains/order/', 'apps/server/src/rpc/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', {}) },
      folders: { 'apps/server': { ...recipes.effect, backend: false } },
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: undefined,
    },
    {
      name: 'an Effect package without domains or backend packages is not a server',
      tree: ['packages/core/src/rpc/'],
      files: { 'package.json': workspaces, 'packages/core/package.json': manifest('core', { effect: '1' }) },
      folders: {},
      file: 'packages/core/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: undefined,
    },
    {
      name: 'migrations inside a domain get the migration names, not the domain names',
      tree: ['apps/server/src/domains/database/migrations/'],
      files: server,
      folders: {},
      file: 'apps/server/src/domains/database/migrations/2026-11-12-10-00-create-news-table.ts',
      rule: 'arch/naming-file',
      expected: ['error', { unique: '^(\\d{4}-\\d{2}-\\d{2}(?:-\\d{2})*|\\d{3,14})[-_]' }],
    },
    {
      name: 'domains allow the Effect file names',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.utils.ts',
      rule: 'arch/naming-file',
      expected: expect.arrayContaining([expect.objectContaining({ message: `Domain files use one of: ${names}. Add a name to layout.files.` })]),
    },
    {
      name: 'the driver name needs a part',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.driver.ts',
      rule: 'arch/naming-file',
      expected: expect.arrayContaining([expect.objectContaining({ pattern: expect.stringContaining('[a-z0-9]+(?:-[a-z0-9]+)*-[a-z0-9]+(?:-[a-z0-9]+)*[.]driver[.]ts') })]),
    },
    {
      name: 'an app name on the domains folder adds to the Effect names',
      tree,
      files: server,
      folders: { 'apps/server/src/domains': { layout: { files: ['*.gateway.ts'] } } },
      file: 'apps/server/src/domains/order/order.gateway.ts',
      rule: 'arch/naming-file',
      expected: expect.arrayContaining([expect.objectContaining({ message: `Domain files use one of: ${names}, *.gateway.ts. Add a name to layout.files.` })]),
    },
    {
      name: 'an app name removed on the domains folder no longer passes',
      tree,
      files: server,
      folders: { 'apps/server/src/domains': { layout: { files: ['!*.prompts.ts'] } } },
      file: 'apps/server/src/domains/order/order.prompts.ts',
      rule: 'arch/naming-file',
      expected: expect.arrayContaining([expect.objectContaining({ message: expect.not.stringContaining('*.prompts.ts') })]),
    },
    {
      name: 'a backend that is not Effect leaves operation files out of the strict check',
      tree: ['apps/server/src/services/order/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', { hono: '1' }) },
      folders: {},
      file: 'apps/server/src/services/order/order-action.create.ts',
      rule: 'arch/naming-file',
      expected: expect.not.arrayContaining([expect.objectContaining({ message: expect.stringMatching(/^Domain files/) })]),
    },
    { name: 'an actions file stops at 1,000 lines', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.actions.ts', rule: 'max-lines', expected: ['error', { max: 1000 }] },
    { name: 'a layer file keeps the default line limit', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.layer.ts', rule: 'max-lines', expected: ['error', { max: 400 }] },
    {
      name: 'an actions file exports domain actions',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order-refund.actions.ts',
      rule: 'arch/files-exports',
      expected: ['error', { stem: 'folder', patterns: ['{domain}Action[A-Z]\\w*'], types: true }],
    },
    { name: 'a layer file has no actions export check', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.layer.ts', rule: 'arch/files-exports', expected: undefined },
    {
      name: 'a queries file calls no write and imports no actions',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.queries.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: { updateTable: reads }, imports: { './*.actions{,.ts}': 'A queries file imports no actions.' } }],
    },
    {
      name: 'an actions file may write',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.actions.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: expect.not.objectContaining({ updateTable: expect.anything() }) }],
    },
    { name: 'a layer file follows the layer file rule', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.layer.ts', rule: 'arch/effect-layer-file', expected: 'error' },
    { name: 'a driver file follows the layer file rule', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order-paypal.driver.ts', rule: 'arch/effect-layer-file', expected: 'error' },
    { name: 'an actions file has no layer file rule', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.actions.ts', rule: 'arch/effect-layer-file', expected: undefined },
    {
      name: 'a workflows file calls no query builder and imports no database',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.workflows.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: { selectFrom: expect.any(String) }, imports: { '**/database': expect.any(String) } }],
    },
    {
      name: 'an actions file may call the query builder',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order.actions.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: expect.not.objectContaining({ selectFrom: expect.anything() }) }],
    },
    { name: 'a constants file holds no function', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.constants.ts', rule: 'arch/files-no-functions', expected: ['error', expect.any(Object)] },
    { name: 'an actions file may hold functions', tree, files: server, folders: {}, file: 'apps/server/src/domains/order/order.actions.ts', rule: 'arch/files-no-functions', expected: undefined },
    {
      name: 'the server source declares no types',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/types-declarations',
      expected: ['error', { modules: true }],
    },
    {
      name: 'the server source writes no inline object shapes',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/types-inline',
      expected: ['error', { variables: true, assertions: true, arguments: true }],
    },
    {
      name: 'files outside the server source keep the plain type checks',
      tree: [...tree, 'apps/server/scripts/'],
      files: server,
      folders: {},
      file: 'apps/server/scripts/seed.ts',
      rule: 'arch/types-inline',
      expected: expect.not.arrayContaining([expect.objectContaining({ variables: true })]),
    },
    {
      name: 'the server source reads no config outside app.config.ts',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { imports: { 'effect/Config': expect.any(String), next: expect.any(String) } }],
    },
    {
      name: 'app.config.ts reads config',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/application/app.config.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { imports: expect.not.objectContaining({ 'effect/Config': expect.anything() }) }],
    },
    { name: 'app.ts may import domain layers', tree, files: server, folders: {}, file: 'apps/server/src/application/app.ts', rule: 'arch/boundaries-imports', expected: 'off' },
    {
      name: 'app.ts imports no other domain file',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/application/app.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { imports: { '**/domains/*/*.{actions,queries,prompts,constants,driver}{,.ts}': expect.any(String) } }],
    },
    {
      name: 'other application files keep the import boundaries',
      tree,
      files: { ...server, 'apps/server/src/application/other.ts': '' },
      folders: {},
      file: 'apps/server/src/application/other.ts',
      rule: 'arch/boundaries-imports',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'JSX outside mails is restricted',
      tree,
      files: server,
      folders: {},
      file: 'apps/server/src/domains/order/order-widget.tsx',
      rule: 'arch/files-restricted',
      expected: ['error', { message: 'Mail templates in mails/ are the only JSX on a server.' }],
    },
    { name: 'a mail template may be JSX', tree, files: server, folders: {}, file: 'apps/server/src/mails/welcome.mail.tsx', rule: 'arch/files-restricted', expected: 'off' },
    { name: 'an rpc handler delegates', tree, files: server, folders: {}, file: 'apps/server/src/rpc/app/orders.ts', rule: 'arch/code-delegate', expected: 'error' },
    { name: 'app.ts has no delegate check', tree, files: server, folders: {}, file: 'apps/server/src/application/app.ts', rule: 'arch/code-delegate', expected: undefined },
    {
      name: 'an app deny call on queries adds to the built-in ones',
      tree,
      files: server,
      folders: { 'apps/server/src/domains/*/*.queries.ts': { deny: { calls: { publish: 'Publish from an action.' } } } },
      file: 'apps/server/src/domains/order/order.queries.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: { updateTable: reads, publish: 'Publish from an action.' } }],
    },
    {
      name: 'an app limit on actions overrides the convention',
      tree,
      files: server,
      folders: { 'apps/server/src/domains/*/*.actions.ts': { limits: { lines: 1500 } } },
      file: 'apps/server/src/domains/order/order.actions.ts',
      rule: 'max-lines',
      expected: ['error', { max: 1500 }],
    },
    {
      name: 'an app export rule on actions overrides the convention',
      tree,
      files: server,
      folders: { 'apps/server/src/domains/*/*.actions.ts': { rules: { 'arch/files-exports': ['error', { stem: 'folder', patterns: ['{domain}[A-Z]\\w*'] }] } } },
      file: 'apps/server/src/domains/order/order.actions.ts',
      rule: 'arch/files-exports',
      expected: ['error', { stem: 'folder', patterns: ['{domain}[A-Z]\\w*'] }],
    },
    {
      name: 'an app turns the delegate check off on rpc',
      tree,
      files: server,
      folders: { 'apps/server/src/rpc': { rules: { 'arch/code-delegate': 'off' } } },
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/code-delegate',
      expected: 'off',
    },
    {
      name: 'an app turns one write call off on queries',
      tree,
      files: server,
      folders: { 'apps/server/src/domains/*/*.queries.ts': { deny: { calls: { updateTable: false } } } },
      file: 'apps/server/src/domains/order/order.queries.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { calls: expect.not.objectContaining({ updateTable: expect.anything() }) }],
    },
    {
      name: 'an app turns the config ban off on the source',
      tree,
      files: server,
      folders: { 'apps/server/src': { deny: { imports: { 'effect/Config': false } } } },
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { imports: expect.not.objectContaining({ 'effect/Config': expect.anything() }) }],
    },
    {
      name: 'without detection no convention is added',
      tree,
      files: server,
      folders: { 'apps/server': recipes.effect },
      detect: false,
      file: 'apps/server/src/rpc/app/orders.ts',
      rule: 'arch/code-delegate',
      expected: undefined,
    },
  ])('$name', (row) => {
    expect({ value: testerPreset(row) }).toMatchObject({ value: row.expected })
  })
})
