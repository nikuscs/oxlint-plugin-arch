import { describe, expect, it } from 'vitest'
import { recipes } from '../../src/preset/preset.ts'
import { testerPreset } from '../utils/tester.utils.ts'
import type { TesterPresetRow } from '../types/tester.types.ts'

describe('preset recipes', () => {
  const manifest = (name: string, dependencies: Record<string, string>) => JSON.stringify({ name, dependencies })
  const workspaces = JSON.stringify({ workspaces: ['apps/*', 'packages/*'] })
  const tailwind = '@import "tailwindcss";'
  const server = { 'package.json': workspaces, 'apps/server/package.json': manifest('server', { hono: '1' }) }

  it.each<TesterPresetRow>([
    {
      name: 'an Effect package gets the effect group',
      files: { 'package.json': workspaces, 'packages/core/package.json': manifest('core', { effect: '1' }) },
      folders: {},
      file: 'packages/core/src/a.ts',
      rule: 'arch/code-traced',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'an Effect app with backend packages gets the effect group',
      tree: ['apps/server/src/rpc/'],
      files: {
        'package.json': workspaces,
        'apps/server/package.json': manifest('server', {
          effect: '1',
          kysely: '1',
          '@orpc/server': '1',
        }),
      },
      folders: {},
      file: 'apps/server/src/a.ts',
      rule: 'arch/code-traced',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'an Effect app with backend packages gets no backend rule',
      tree: ['apps/server/src/rpc/'],
      files: {
        'package.json': workspaces,
        'apps/server/package.json': manifest('server', {
          effect: '1',
          kysely: '1',
          '@orpc/server': '1',
        }),
      },
      folders: {},
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: undefined,
    },
    {
      name: 'an Effect package with React components is a UI kit',
      tree: ['packages/ui/src/components/order/'],
      files: { 'package.json': workspaces, 'packages/ui/package.json': manifest('ui', { effect: '1', react: '1' }), 'packages/ui/src/styles.css': tailwind },
      folders: {},
      file: 'packages/ui/src/components/order/order-card.tsx',
      rule: 'arch/files-components-only',
      expected: undefined,
    },
    {
      name: 'an Effect package with React components gets no effect group',
      tree: ['packages/ui/src/components/order/'],
      files: { 'package.json': workspaces, 'packages/ui/package.json': manifest('ui', { effect: '1', react: '1' }), 'packages/ui/src/styles.css': tailwind },
      folders: {},
      file: 'packages/ui/src/a.ts',
      rule: 'arch/code-traced',
      expected: undefined,
    },
    {
      name: 'an Effect package with React pages is a frontend, not a UI kit',
      tree: ['packages/web/src/pages/', 'packages/web/src/components/order/'],
      files: { 'package.json': workspaces, 'packages/web/package.json': manifest('web', { effect: '1', react: '1' }) },
      folders: {},
      file: 'packages/web/src/components/order/order-card.tsx',
      rule: 'arch/files-components-only',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'an Effect package with a link file gets the react recipe',
      files: { 'package.json': workspaces, 'packages/web/package.json': manifest('web', { effect: '1', react: '1' }), 'packages/web/src/link.tsx': '' },
      folders: {},
      file: 'packages/web/src/a.tsx',
      rule: 'arch/react-memo',
      expected: 'error',
    },
    {
      name: 'an Effect app on TanStack gets the tanstack recipe',
      tree: ['apps/web/src/routes/'],
      files: { 'package.json': workspaces, 'apps/web/package.json': manifest('web', { effect: '1', '@tanstack/react-start': '1' }) },
      folders: {},
      file: 'apps/web/src/routes/index.tsx',
      rule: 'arch/files-route',
      expected: ['error', { export: 'Route' }],
    },
    {
      name: 'an Effect package with React and no components gets the effect group',
      files: { 'package.json': workspaces, 'packages/core/package.json': manifest('core', { effect: '1', react: '1' }) },
      folders: {},
      file: 'packages/core/src/a.ts',
      rule: 'arch/code-traced',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'without Effect a React app with a backend package stays a backend',
      tree: ['apps/server/src/components/', 'apps/server/src/rpc/'],
      files: { 'package.json': workspaces, 'apps/server/package.json': manifest('server', { react: '1', hono: '1' }) },
      folders: {},
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: 'error',
    },
    {
      name: 'without Effect a React package with pages gets the react recipe',
      tree: ['packages/web/src/pages/'],
      files: { 'package.json': workspaces, 'packages/web/package.json': manifest('web', { react: '1' }) },
      folders: {},
      file: 'packages/web/src/a.tsx',
      rule: 'arch/react-memo',
      expected: 'error',
    },
    {
      name: 'a folder set to the Effect recipe drops the detected backend',
      tree: ['apps/server/src/services/', 'apps/server/src/rpc/'],
      files: server,
      folders: { 'apps/server': recipes.effect },
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: undefined,
    },
    {
      name: 'a folder set to the Effect recipe gets the effect group',
      tree: ['apps/server/src/services/', 'apps/server/src/rpc/'],
      files: server,
      folders: { 'apps/server': recipes.effect },
      file: 'apps/server/src/a.ts',
      rule: 'arch/code-traced',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'a folder set to the library recipe drops the detected Effect group',
      files: { 'package.json': workspaces, 'packages/i18n/package.json': manifest('i18n', { effect: '1' }) },
      folders: { 'packages/i18n': recipes.library },
      file: 'packages/i18n/src/a.ts',
      rule: 'arch/code-traced',
      expected: undefined,
    },
    {
      name: 'a spread recipe drops the detected UI kit',
      tree: ['packages/ui/src/components/order/'],
      files: { 'package.json': workspaces, 'packages/ui/package.json': manifest('ui', { react: '1' }), 'packages/ui/src/styles.css': tailwind },
      folders: { 'packages/ui': { ...recipes.react, tailwind: false } },
      file: 'packages/ui/src/components/order/order-card.tsx',
      rule: 'arch/files-components-only',
      expected: ['error', expect.any(Object)],
    },
    {
      name: 'a hand-written backend setting merges over the detected backend',
      tree: ['apps/server/src/services/order/'],
      files: server,
      folders: { 'apps/server': { backend: { registry: false } } },
      file: 'apps/server/src/services/order/order.service.ts',
      rule: 'arch/backend-sql-like',
      expected: 'error',
    },
    {
      name: 'a hand-written console setting merges over the detected backend',
      tree: ['apps/server/src/services/', 'apps/server/src/rpc/'],
      files: server,
      folders: { 'apps/server': { console: true } },
      file: 'apps/server/src/rpc/a.ts',
      rule: 'arch/boundaries-rpc-database',
      expected: 'error',
    },
    {
      name: 'a folder set to a recipe drops the detected flat services',
      tree: ['apps/web/src/services/billing/'],
      files: {
        'package.json': workspaces,
        'apps/web/package.json': manifest('web', { '@tanstack/react-start': '1' }),
        'apps/web/src/services/a.client.ts': '',
        'apps/web/src/services/b.client.ts': '',
      },
      folders: { 'apps/web': recipes.tanstack },
      file: 'apps/web/src/services/billing/deep/billing.client.ts',
      rule: 'arch/files-restricted',
      expected: ['error', { message: expect.stringMatching(/^This folder uses exactly one owning domain directory/) }],
    },
    {
      name: 'a root set to a recipe keeps the root import deny',
      files: { 'package.json': manifest('app', { hono: '1' }) },
      folders: { '.': recipes.backend },
      file: 'src/a.ts',
      rule: 'arch/boundaries-deny',
      expected: ['error', { imports: { 'framer-motion': 'Use motion/react.' } }],
    },
    {
      name: 'a detected backend checks oRPC outputs in rpc/api',
      tree: ['apps/server/src/services/', 'apps/server/src/rpc/api/'],
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/api/orders.ts',
      rule: 'arch/backend-orpc-output',
      expected: ['error', { handler: 'handler', output: 'output' }],
    },
    {
      name: 'orpc set to false leaves oRPC outputs unchecked',
      tree: ['apps/server/src/services/', 'apps/server/src/rpc/api/'],
      files: server,
      folders: { 'apps/server': { orpc: false } },
      file: 'apps/server/src/rpc/api/orders.ts',
      rule: 'arch/backend-orpc-output',
      expected: undefined,
    },
    {
      name: 'a backend without rpc/api gets no oRPC output check',
      tree: ['apps/server/src/services/'],
      files: server,
      folders: {},
      file: 'apps/server/src/rpc/api/orders.ts',
      rule: 'arch/backend-orpc-output',
      expected: undefined,
    },
  ])('$name', (row) => {
    expect({ value: testerPreset(row) }).toMatchObject({ value: row.expected })
  })
})
