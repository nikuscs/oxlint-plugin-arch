import { describe, it } from 'vitest'
import { layoutCallArguments } from '../../../src/rules/layout/layout-call-arguments.ts'
import { testerRun } from '../../utils/tester.utils.ts'

describe('arch/layout-call-arguments', () => {
  it.each([
    { name: 'two arguments stay inline', code: 'save(a, b)' },
    { name: 'already split call passes', code: 'save(\n  a,\n  b,\n  c,\n)' },
    { name: 'already split commented call passes', code: 'save(\n  a,\n  /* keep */ b,\n  c\n)' },
    { name: 'already split parenthesized call passes', code: 'save(\n  (a),\n  b,\n  c\n)' },
    { name: 'a multiline callback skips the call', code: "describe('x', options, () => {\n  run()\n})" },
    { name: 'min raises the threshold', code: 'save(a, b, c)', options: { min: 4 } },
    { name: 'a split new with a spread and trailing comma passes', code: 'new Box(\n  a,\n  b,\n  ...rest,\n)' },
    { name: 'a multiline function callback skips the call', code: "describe('x', options, function () {\n  run()\n})" },
    { name: 'splits a call', code: 'save(a, b, c)', output: 'save(\n  a,\n  b,\n  c\n)', errors: ['multiline'] },
    { name: 'splits a new expression with a spread', code: 'new Box(a, b, ...rest)', output: 'new Box(\n  a,\n  b,\n  ...rest\n)', errors: ['multiline'] },
    { name: 'keeps a trailing comma', code: 'save(a, b, c,)', output: 'save(\n  a,\n  b,\n  c,\n)', errors: ['multiline'] },
    { name: 'splits a new expression', code: 'new Box(a, b, c)', output: 'new Box(\n  a,\n  b,\n  c\n)', errors: ['multiline'] },
    { name: 'splits after type arguments', code: 'save<T>(a, b, c)', output: 'save<T>(\n  a,\n  b,\n  c\n)', errors: ['multiline'] },
    { name: 'splits an optional call', code: 'save?.(a, b, c)', output: 'save?.(\n  a,\n  b,\n  c\n)', errors: ['multiline'] },
    { name: 'reflows a partly split call', code: 'save(a,\n  b,\n  c)', output: 'save(\n  a,\n  b,\n  c\n)', errors: ['multiline'] },
    { name: 'a one-line callback still splits', code: 'save(a, b, () => c)', output: 'save(\n  a,\n  b,\n  () => c\n)', errors: ['multiline'] },
    {
      name: 'a multiline object argument still splits',
      code: 'save(a, b, {\n  value: c\n})',
      output: 'save(\n  a,\n  b,\n  {\n  value: c\n}\n)',
      errors: ['multiline'],
    },
    { name: 'min and indent options', code: '  save(a, b)', options: { min: 2, indent: 4 }, output: '  save(\n      a,\n      b\n  )', errors: ['multiline'] },
    { name: 'tab indent option', code: '\tsave(a, b, c)', options: { indent: 'tab' }, output: '\tsave(\n\t\ta,\n\t\tb,\n\t\tc\n\t)', errors: ['multiline'] },
    { name: 'keeps CRLF line endings', code: 'save(a, b, c)\r\n', output: 'save(\r\n  a,\r\n  b,\r\n  c\r\n)\r\n', errors: ['multiline'] },
    { name: 'a comment prevents a fix but not a report', code: 'save(a, /* keep */ b, c)', output: null, errors: ['multiline'] },
    { name: 'a parenthesized first argument reports without a fix', code: 'save((a), b, c)', output: null, errors: ['multiline'] },
    { name: 'a parenthesized middle argument reports without a fix', code: 'save(a, (b), c)', output: null, errors: ['multiline'] },
    { name: 'a parenthesized last argument reports without a fix', code: 'save(a, b, (c))', output: null, errors: ['multiline'] },
    { name: 'split false turns the split off', code: 'save(a, b, c)', options: { split: false } },
    { name: 'hug passes a last callback hugging the call', code: 'run(a, () => {\n  go()\n})', options: { split: false, hug: { max: 80 } } },
    { name: 'hug passes split arguments', code: 'run(\n  a,\n  b(\n    c,\n  ),\n)', options: { split: false, hug: { max: 80 } } },
    {
      name: 'hug splits a multi-line call that cannot hug',
      code: 'run(a, b(\n  c,\n))',
      options: { split: false, hug: { max: 80 } },
      output: 'run(\n  a,\n  b(\n  c,\n)\n)',
      errors: ['hug'],
    },
    {
      name: 'hug keeps the trailing comma as written',
      code: 'run(a, b(\n  c,\n),)',
      options: { split: false, hug: { max: 80 } },
      output: 'run(\n  a,\n  b(\n  c,\n),\n)',
      errors: ['hug'],
    },
    {
      name: 'hug prefers a hugged last callback',
      code: 'run(\n  a,\n  () => {\n    go()\n  },\n)',
      options: { split: false, hug: { max: 80 } },
      output: 'run(a, () => {\n    go()\n  },)',
      errors: ['prefer'],
    },
    { name: 'hug skips a hug past max', code: 'run(\n  a,\n  () => {\n    go()\n  },\n)', options: { split: false, hug: { max: 10 } } },
    { name: 'hug skips pipe calls', code: 'x.pipe(\n  a,\n  () => {\n    go()\n  },\n)', options: { split: false, hug: { max: 80 } } },
    { name: 'hug skips a commented call', code: 'run(a, b(\n  c, // keep\n))', options: { split: false, hug: { max: 80 } } },
    { name: 'join passes a call on one line', code: 'save(a, b)', options: { split: false, join: { max: 80 } } },
    { name: 'join joins a short split call', code: 'save(\n  a,\n  b,\n)', options: { split: false, join: { max: 80 } }, output: 'save(a, b,)', errors: ['join'] },
    { name: 'join joins split parameters', code: 'function save(\n  a,\n  b\n) {}', options: { split: false, join: { max: 80 } }, output: 'function save(a, b) {}', errors: ['join'] },
    { name: 'join leaves a call past max', code: 'save(\n  alpha,\n  beta,\n)', options: { split: false, join: { max: 10 } } },
    { name: 'join leaves three arguments', code: 'save(\n  a,\n  b,\n  c,\n)', options: { split: false, join: { max: 80 } } },
    { name: 'join leaves kept callees', code: 'Layer.mergeAll(\n  a,\n  b,\n)', options: { split: false, join: { max: 80, keep: ['Layer.mergeAll'] } } },
    { name: 'join leaves calls nested past nesting', code: 'save(\n  a(b(c)),\n)', options: { split: false, join: { max: 80, nesting: 2 } } },
    { name: 'join leaves a commented call', code: 'save(\n  a, // keep\n  b,\n)', options: { split: false, join: { max: 80 } } },
    {
      name: 'join items raises the joined count up to min - 1',
      code: 'save(\n  a,\n  b,\n  c,\n)',
      options: { min: 4, join: { max: 80, items: 3 } },
      output: 'save(a, b, c,)',
      errors: ['join'],
    },
    { name: 'join leaves three arguments by default under a higher min', code: 'save(\n  a,\n  b,\n  c,\n)', options: { min: 4, join: { max: 80 } } },
    { name: 'join and split leave min arguments', code: 'save(\n  a,\n  b,\n  c,\n  d,\n)', options: { min: 4, join: { max: 80 } } },
    { name: 'join without split leaves three arguments under a higher min', code: 'save(\n  a,\n  b,\n  c,\n)', options: { split: false, min: 4, join: { max: 80 } } },
    { name: 'join without split still joins two arguments with min 2', code: 'save(\n  a,\n  b,\n)', options: { split: false, min: 2, join: { max: 80 } }, output: 'save(a, b,)', errors: ['join'] },
    { name: 'join and split leave min arguments split', code: 'save(\n  a,\n  b,\n)', options: { min: 2, join: { max: 80 } } },
    { name: 'join and split join below min', code: 'save(\n  a,\n)', options: { min: 2, join: { max: 80 } }, output: 'save(a,)', errors: ['join'] },
    { name: 'join counts the trailing comma toward max', code: 'save(\n  a,\n  b,\n)', options: { split: false, join: { max: 10 } } },
    { name: 'pipe passes below min', code: 'value.pipe(a, b)', options: { split: false, pipe: { min: 3 } } },
    { name: 'pipe leaves other calls to split', code: 'save(a, b, c)', options: { split: false, pipe: { min: 3 } } },
    { name: 'pipe passes when already split', code: 'Function.pipe(\n  a,\n  b,\n  c,\n)', options: { split: false, pipe: { min: 3 } } },
    {
      name: 'pipe splits a data-first pipe while split is off',
      code: 'const parts = Function.pipe(search, split, trim, filter)',
      options: { split: false, pipe: { min: 3 } },
      output: 'const parts = Function.pipe(\n  search,\n  split,\n  trim,\n  filter\n)',
      errors: ['pipe'],
    },
    {
      name: 'pipe splits a method pipe and keeps the comma style',
      code: 'run.pipe(retry, timeout, log,)',
      options: { split: false, pipe: { min: 3 } },
      output: 'run.pipe(\n  retry,\n  timeout,\n  log,\n)',
      errors: ['A pipe with 3+ steps puts each step on its own line.'],
    },
    { name: 'pipe min wins over min', code: 'run.pipe(a, b)', options: { min: 3, pipe: { min: 2 } }, output: 'run.pipe(\n  a,\n  b\n)', errors: ['pipe'] },
    { name: 'pipe reports a comment without a fix', code: 'run.pipe(a, /* x */ b, c)', options: { split: false, pipe: { min: 3 } }, output: null, errors: ['pipe'] },
    { name: 'pipe methods are configurable', code: 'run.chain(a, b, c)', options: { split: false, pipe: { min: 3, methods: ['chain'] } }, output: 'run.chain(\n  a,\n  b,\n  c\n)', errors: ['pipe'] },
    { name: 'pipe keeps a split one-step pipe from join', code: 'change.pipe(\n  mapError(f),\n)', options: { split: false, pipe: { min: 2 }, join: { max: 140 } } },
    { name: 'join still joins a one-step pipe without pipe', code: 'change.pipe(\n  mapError(f),\n)', options: { split: false, join: { max: 140 } }, output: 'change.pipe(mapError(f),)', errors: ['join'] },
  ])('$name', (row) => testerRun(layoutCallArguments, row))
})
