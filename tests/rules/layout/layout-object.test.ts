import { describe, it } from 'vitest'
import { layoutObject } from '../../../src/rules/layout/layout-object.ts'
import { testerRun } from '../../utils/tester.utils.ts'

describe('arch/layout-object', () => {
  it.each([
    { name: 'two properties stay inline', code: 'save({ id, name })' },
    { name: 'already split object passes', code: 'save({\n  id,\n  name,\n  email,\n})' },
    { name: 'objects outside calls pass by default', code: 'const row = { id, name, email }' },
    { name: 'min raises the threshold', code: 'save({ a: 1, b: 2, c: 3 })', options: { min: 4 } },
    { name: 'plain arguments pass', code: 'save(id, name, email)' },
    { name: 'a comment blocks the fix', code: 'save({ a: 1, b: 2, c: 3 /* keep */ })', output: null, errors: ['callArgs'] },
    { name: 'splits a call argument', code: 'save({ id, name, email })', output: 'save({\n  id,\n  name,\n  email\n})', errors: ['callArgs'] },
    { name: 'keeps a trailing comma', code: 'save({ id, name, email, })', output: 'save({\n  id,\n  name,\n  email,\n})', errors: ['callArgs'] },
    { name: 'splits a new argument', code: 'new Box({ id, name, email })', output: 'new Box({\n  id,\n  name,\n  email\n})', errors: ['callArgs'] },
    { name: 'splits a spread', code: 'save({ ...row, id, name })', output: 'save({\n  ...row,\n  id,\n  name\n})', errors: ['callArgs'] },
    { name: 'splits a middle argument', code: 'save(1, { id, name, email }, 2)', output: 'save(1, {\n  id,\n  name,\n  email\n}, 2)', errors: ['callArgs'] },
    {
      name: 'the default scope leaves a nested object inline',
      code: 'save({ a: 1, b: 2, c: { d: 1, e: 2, f: 3 } })',
      output: 'save({\n  a: 1,\n  b: 2,\n  c: { d: 1, e: 2, f: 3 }\n})',
      errors: ['callArgs'],
    },
    {
      name: 'scope all checks every object',
      code: 'const row = { id, name, email }',
      options: { scope: 'all' },
      output: 'const row = {\n  id,\n  name,\n  email\n}',
      errors: ['always'],
    },
    {
      name: 'scope all indents a nested object',
      code: 'const row = {\n  a: 1,\n  b: 2,\n  c: { d: 1, e: 2, f: 3 }\n}',
      options: { scope: 'all' },
      output: 'const row = {\n  a: 1,\n  b: 2,\n  c: {\n    d: 1,\n    e: 2,\n    f: 3\n  }\n}',
      errors: ['always'],
    },
    { name: 'min option', code: 'save({ id, name })', options: { min: 2 }, output: 'save({\n  id,\n  name\n})', errors: ['callArgs'] },
    {
      name: 'tab indent',
      code: '\tsave({ id, name, email })',
      options: { indent: 'tab' },
      output: '\tsave({\n\t\tid,\n\t\tname,\n\t\temail\n\t})',
      errors: ['callArgs'],
    },
    { name: 'keeps CRLF line endings', code: 'save({ id, name, email })\r\n', output: 'save({\r\n  id,\r\n  name,\r\n  email\r\n})\r\n', errors: ['callArgs'] },
    {
      name: 'splits a nested call argument with its indent',
      code: "function run() {\n  execFileSync(cmd, args, { encoding: 'utf8', maxBuffer: 1, stdio: ['ignore', 'pipe', 'inherit'] });\n}",
      output: "function run() {\n  execFileSync(cmd, args, {\n    encoding: 'utf8',\n    maxBuffer: 1,\n    stdio: ['ignore', 'pipe', 'inherit']\n  });\n}",
      errors: ['callArgs'],
    },
    { name: 'join unset leaves a short split object', code: 'save({\n  id,\n  name,\n})' },
    { name: 'join joins a short split object', code: 'save({\n  id,\n  name\n})', options: { join: { max: 80 } }, output: 'save({ id, name })', errors: ['join'] },
    { name: 'join keeps a trailing comma', code: 'save({\n  id,\n  name,\n})', options: { join: { max: 80 } }, output: 'save({ id, name, })', errors: ['join'] },
    { name: 'join leaves an object with min properties split', code: 'save({\n  a,\n  b,\n  c,\n})', options: { join: { max: 80 } } },
    { name: 'join joins min - 1 properties', code: 'save({\n  a\n})', options: { min: 2, join: { max: 80 } }, output: 'save({ a })', errors: ['join'] },
    { name: 'join leaves min properties with a lower min', code: 'save({\n  a,\n  b\n})', options: { min: 2, join: { max: 80 } } },
    { name: 'join joins an object that fits max exactly', code: 'save({\n  id,\n  name\n})', options: { join: { max: 18 } }, output: 'save({ id, name })', errors: ['join'] },
    { name: 'join leaves an object one column past max', code: 'save({\n  id,\n  name\n})', options: { join: { max: 17 } } },
    { name: 'join counts the trailing comma toward max', code: 'save({\n  id,\n  name,\n})', options: { join: { max: 18 } } },
    { name: 'join leaves a commented object', code: 'save({\n  id, // keep\n  name,\n})', options: { join: { max: 80 } } },
    { name: 'join leaves an object value', code: 'save({\n  id,\n  row: { a },\n})', options: { join: { max: 80 } } },
    { name: 'join leaves an array value', code: 'save({\n  id,\n  rows: [a],\n})', options: { join: { max: 80 } } },
    { name: 'join leaves an arrow value', code: 'save({\n  id,\n  run: () => id,\n})', options: { join: { max: 80 } } },
    { name: 'join leaves a method', code: 'save({\n  id,\n  run() {},\n})', options: { join: { max: 80 } } },
    { name: 'join leaves a multi-line value', code: 'save({\n  id: load(\n    a,\n  ),\n})', options: { join: { max: 80 } } },
    { name: 'join keep leaves a kept callee by method name', code: 'z.object({\n  id: z.string(),\n})', options: { join: { max: 80, keep: ['object'] } } },
    { name: 'join keep leaves a kept callee by full name', code: 'z.object({\n  id: z.string(),\n})', options: { join: { max: 80, keep: ['z.object'] } } },
    { name: 'join keep joins other callees', code: 'save({\n  id,\n})', options: { join: { max: 80, keep: ['object'] } }, output: 'save({ id, })', errors: ['join'] },
    { name: 'join skips objects outside calls by default', code: 'const row = {\n  id,\n}', options: { join: { max: 80 } } },
    {
      name: 'join with scope all joins any object',
      code: 'const row = {\n  id,\n  name\n}',
      options: { scope: 'all', join: { max: 80 } },
      output: 'const row = { id, name }',
      errors: ['join'],
    },
    { name: 'join keeps CRLF around the object', code: 'save({\r\n  id,\r\n  name\r\n})\r\n', options: { join: { max: 80 } }, output: 'save({ id, name })\r\n', errors: ['join'] },
  ])('$name', (row) => testerRun(layoutObject, row))
})
