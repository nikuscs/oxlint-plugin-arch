import { describe, it } from 'vitest'
import { typesInline } from '../../../src/rules/types/types-inline.ts'
import { testerRun } from '../../utils/tester.utils.ts'

describe('arch/types-inline', () => {
  it.each([
    { name: 'named types pass', code: 'function save(user: User): SaveResult { return run(user) }' },
    { name: 'a named type argument passes', code: 'const save = (user: User): Promise<SaveResult> => run(user)' },
    { name: 'no annotations pass', code: 'function load() { return { id: 1 } }' },
    { name: 'a default value is not an annotation', code: "function save(user: User = make({ id: 'one' })) {}" },
    { name: 'variable annotations are skipped', code: "const user: { id: string } = { id: 'one' }" },
    { name: 'interface methods are skipped', code: 'interface Service { save(user: { id: string }): { ok: boolean } }' },
    {
      name: 'type declarations are skipped',
      code: 'type User = { id: string }; interface Result { ok: boolean }; type Save = (user: { id: string }) => { ok: boolean }',
    },
    { name: 'parameters off', code: 'function save(user: { id: string }): SaveResult {}', options: { parameters: false } },
    { name: 'returns off', code: 'function save(user: User): { ok: boolean } {}', options: { returns: false } },
    { name: 'both off', code: 'function save(user: { id: string }): { ok: boolean } {}', options: { parameters: false, returns: false } },
    { name: 'functions off', code: 'function save(run: (user: User) => SaveResult): () => SaveResult {}', options: { functions: false } },
    { name: 'smaller than min', code: 'function save(user: { id: string }): { ok: boolean } {}', options: { min: 2 } },
    { name: 'a primitive return union passes', code: 'function get(): string | undefined { return undefined }' },
    { name: 'an empty input below the minimum passes', code: 'function save(input: {}): { ok: boolean } { return { ok: true } }', options: { min: 2 } },
    { name: 'a nested single member below the minimum passes', code: 'function save(input: { nested: { id: string } }) {}', options: { min: 2 } },
    { name: 'an object parameter', code: 'function save(user: { id: string }) {}', errors: ['inlineType'] },
    { name: 'an empty object', code: 'function save(user: {}) {}', errors: ['inlineType'] },
    { name: 'a destructured parameter', code: 'function save({ id }: { id: string }) {}', errors: ['inlineType'] },
    { name: 'a defaulted parameter', code: "function save(user: { id: string } = { id: 'one' }) {}", errors: ['inlineType'] },
    { name: 'a rest parameter', code: 'function save(...users: { id: string }[]) {}', errors: ['inlineType'] },
    { name: 'an arrow', code: 'const save = (user: { id: string }) => user', errors: ['inlineType'] },
    { name: 'an inline callback', code: 'users.map((user: { id: string }) => user.id)', errors: ['inlineType'] },
    { name: 'an object method', code: 'const service = { save(user: { id: string }) {} }', errors: ['inlineType'] },
    { name: 'a parameter property', code: 'class Service { constructor(private user: { id: string }) {} }', errors: ['inlineType'] },
    { name: 'an abstract method', code: 'abstract class Service { abstract save(user: { id: string }): void }', errors: ['inlineType'] },
    { name: 'a declared function', code: 'declare function save(user: { id: string }): { ok: boolean }', errors: ['inlineType', 'inlineType'] },
    { name: 'a return type', code: 'function save(user: User): { ok: boolean } {}', errors: ['inlineType'] },
    { name: 'inside a type argument', code: 'async function save(): Promise<{ ok: boolean }> {}', errors: ['inlineType'] },
    { name: 'each union member', code: 'function save(user: { id: string } | { name: string }) {}', errors: ['inlineType', 'inlineType'] },
    { name: 'a nested object reports once', code: 'function save(user: { team: { id: string }; run: () => void }) {}', errors: ['inlineType'] },
    { name: 'a function type', code: 'function save(): () => void {}', errors: ['inlineType'] },
    { name: 'a constructor type', code: 'function make(factory: new () => Service) {}', errors: ['inlineType'] },
    { name: 'a function type reports once', code: 'function save(run: (user: { id: string }) => { ok: boolean }) {}', errors: ['inlineType'] },
    {
      name: 'functions off still reports objects',
      code: 'function save(run: (user: { id: string }) => void) {}',
      options: { functions: false },
      errors: ['inlineType'],
    },
    {
      name: 'parameters off still reports returns',
      code: 'function save(user: { id: string }): { ok: boolean } {}',
      options: { parameters: false },
      errors: ['inlineType'],
    },
    {
      name: 'returns off still reports parameters',
      code: 'function save(user: { id: string }): { ok: boolean } {}',
      options: { returns: false },
      errors: ['inlineType'],
    },
    { name: 'min reached', code: 'function save(user: { id: string; name: string }) {}', options: { min: 2 }, errors: ['inlineType'] },
    {
      name: 'min reached by a nested object',
      code: 'function save(user: { team: { id: string; name: string } }) {}',
      options: { min: 2 },
      errors: ['inlineType'],
    },
    { name: 'min ignores function types', code: 'function save(run: (user: User) => SaveResult) {}', options: { min: 10 }, errors: ['inlineType'] },
    { name: 'a function expression input object', code: 'const save = function (input: { id: string }) { return input }', errors: ['inlineType'] },
    { name: 'a destructured input with a default', code: 'function save({ id }: { id: string } = { id: "one" }) {}', errors: ['inlineType'] },
    { name: 'a destructured tuple input object', code: 'function save([input]: [{ id: string }]) {}', errors: ['inlineType'] },
    {
      name: 'a class method with inline input and result',
      code: 'class Service { save(input: { id: string }): { ok: boolean } { return { ok: true } } }',
      errors: ['inlineType', 'inlineType'],
    },
    { name: 'an inline readonly input', code: 'function save(input: Readonly<{ id: string }>) {}', errors: ['inlineType'] },
    { name: 'an inline intersection member', code: 'function save(input: Input & { extra: boolean }) {}', errors: ['inlineType'] },
  ])('$name', (row) => testerRun(typesInline, row))
})
