import { describe, it } from 'vitest'
import { codeMutableState } from '../../../src/rules/code/code-mutable-state.ts'
import { testerRun } from '../../utils/tester.utils.ts'

describe('arch/code-mutable-state', () => {
  it.each([
    { name: 'constant binding passes', code: 'const cache = new Map()' },
    { name: 'function-local bindings pass', code: 'function run() { let count = 0; var total = 1; return count + total }' },
    { name: 'block-scoped let passes', code: '{ let hidden = 1 }' },
    { name: 'loop-scoped let passes', code: 'for (let index = 0; index < 1; index++) {}' },
    { name: 'ambient declarations pass', code: 'declare let first: number; export declare var second: number' },
    { name: 'ambient namespace passes', code: 'declare namespace API { var value: number; let other: number }' },
    { name: 'global augmentation passes', code: 'export {}; declare global { var value: number }' },
    { name: 'ambient module passes', code: "declare module 'external' { var value: number }" },
    { name: 'static block is a local scope', code: 'class Store { static { var count = 0 } }' },
    { name: 'unchecked var passes', code: 'var cache = {}', options: { kinds: ['let'] } },
    { name: 'unchecked let passes', code: 'let cache = {}', options: { kinds: ['var'] } },
    { name: 'allowed binding passes', code: 'let cache = {}', options: { allow: '^cache$' } },
    { name: 'multiple allow patterns pass', code: 'let cache = {}, store = 1', options: { allow: ['^cache$', '^store$'] } },
    { name: 'a module const passes', code: 'const limit = 1' },
    { name: 'an exported const passes', code: 'export const limit = 1' },
    { name: 'declare let passes', code: 'declare let ambient: number' },
    { name: 'export declare let passes', code: 'export declare let ambient: number' },
    { name: 'declare var passes', code: 'declare var ambient: number' },
    { name: 'a global augmentation with let passes', code: 'export {}; declare global { var value: number; let other: number }' },
    { name: 'a short ambient module passes', code: "declare module 'x' { var value: number }" },
    { name: 'a class field passes', code: 'class Store { count = 0 }' },
    { name: 'const destructuring passes', code: 'const { a, b } = values' },
    { name: 'allowed names on separate lines pass', code: 'let cache = {}\nexport let unsafeStore = 1', options: { allow: '^(cache|unsafe)' } },
    { name: 'allowed destructured names pass', code: 'let { cache, rest } = values', options: { allow: '^(cache|rest)$' } },
    { name: 'each allow pattern passes its own line', code: 'let cache = {}\nlet store = 1', options: { allow: ['^cache$', '^store$'] } },
    { name: 'module let fails', code: 'let cache = new Map()', errors: ['moduleState'] },
    { name: 'module var fails', code: 'var count = 0', errors: ['moduleState'] },
    { name: 'exported let fails', code: 'export let count = 0', errors: ['moduleState'] },
    { name: 'block var leaks to the module', code: 'if (enabled) { var cache = {} }', errors: ['moduleState'] },
    { name: 'loop var leaks to the module', code: 'for (var item of items) {}', errors: ['moduleState'] },
    { name: 'each declarator reports', code: 'let count = 0, total = 1', errors: ['moduleState', 'moduleState'] },
    { name: 'renamed nested binding reports', code: 'let { nested: { inner: renamed } } = values', errors: ['moduleState'] },
    { name: 'array holes are ignored', code: 'let [first, , second] = values', errors: ['moduleState', 'moduleState'] },
    { name: 'rest bindings report', code: 'let [head, ...tail] = values', errors: ['moduleState', 'moduleState'] },
    { name: 'object rest binding reports', code: 'let { ...rest } = values', errors: ['moduleState'] },
    { name: 'defaulted binding reports', code: 'let { value = 1 } = values', errors: ['moduleState'] },
    { name: 'allow list applies per destructured binding', code: 'let { cache, other } = values', options: { allow: '^cache$' }, errors: ['moduleState'] },
    { name: 'selected kind still reports', code: 'var count = 0; let total = 1', options: { kinds: ['var'] }, errors: ['moduleState'] },
    { name: 'a module let', code: 'let count = 0', errors: ['moduleState'] },
    { name: 'a block var used later', code: 'if (enabled) { var cache = {} }; cache.x = 1', errors: ['moduleState'] },
    { name: 'a var in a bare block', code: '{ var hidden = 1 }', errors: ['moduleState'] },
    { name: 'a var in a for loop', code: 'for (var index = 0; index < 1; index++) {}', errors: ['moduleState'] },
    { name: 'a var in a for-in loop', code: 'for (var key in object) {}', errors: ['moduleState'] },
    { name: 'an exported var', code: 'export var count = 0', errors: ['moduleState'] },
    { name: 'two destructured lets', code: 'let { a, b } = values', errors: ['moduleState', 'moduleState'] },
    { name: 'a renamed destructured let', code: 'let { a: renamed } = values', errors: ['moduleState'] },
    { name: 'a nested destructured let', code: 'let { nested: { inner } } = values', errors: ['moduleState'] },
    { name: 'a defaulted destructured let', code: 'let { a = 1 } = values', errors: ['moduleState'] },
    { name: 'a let outside the allow list', code: 'let cache = {}\nlet other = 1', options: { allow: '^cache$' }, errors: ['moduleState'] },
    { name: 'a let when only let is checked', code: 'var count = 0\nlet total = 1', options: { kinds: ['let'] }, errors: ['moduleState'] },
  ])('$name', (row) => testerRun(codeMutableState, row))
})
