import { describe, it } from 'vitest'
import { boundariesImports } from '../../../src/rules/boundaries/boundaries-imports.ts'
import { testerRun } from '../../utils/tester.utils.ts'

describe('arch/boundaries-imports', () => {
  it.each([
    {
      name: 'public backend entrypoint',
      filename: '/project/web/chat.ts',
      code: "import { client } from '@app/server/client'",
      options: { web: ['/project/web'], backendPackages: ['@app/server'], entrypoints: ['@app/server/client'] },
    },
    {
      name: 'private helpers stay inside their domain',
      filename: '/project/web/services/chat/chat.service.ts',
      code: "import { normalize } from './chat-driver.normalize'",
      options: { web: ['/project/web'], roles: ['driver'] },
    },
    {
      name: 'public services cross domain boundaries',
      filename: '/project/web/services/chat/chat.service.ts',
      code: "import { users } from '../user/user.service'",
      options: { web: ['/project/web'], roles: ['driver'] },
    },
    {
      name: 'portable library imports its own contract',
      filename: '/project/web/lib/fade.utils.ts',
      code: "import type { FadeOptions } from '../types/fade.types'",
      options: { web: ['/project/web'], portable: true },
    },
    {
      name: 'portable library uses its own import type',
      filename: '/project/web/lib/fade.ts',
      code: "type Options = import('../types/fade.types').FadeOptions",
      options: { web: ['/project/web'], portable: true },
    },
    {
      name: 'portable restriction is opt-in',
      filename: '/project/web/lib/fade.ts',
      code: "import { fade } from '../services/fade/fade.utils'",
      options: { web: ['/project/web'] },
    },
    { name: 'client services allow UI type imports', filename: 'chat.client.ts', code: "import type { ReactNode } from 'react'" },
    {
      name: 'domain types may type-import implementations',
      filename: '/project/web/types/chat.types.ts',
      code: "import type { chat } from '../services/chat/chat.service'",
      options: { web: ['/project/web'] },
    },
    {
      name: 'frontend cannot import backend internals',
      filename: '/project/web/chat.ts',
      code: "import { chats } from '@app/server/db/chats'",
      options: { web: ['/project/web'], backendPackages: ['@app/server'], entrypoints: ['@app/server/client'] },
      errors: ['boundary'],
    },
    {
      name: 'backend aliases resolve before checking ownership',
      filename: '/project/web/chat.ts',
      code: "import type { Chat } from '@backend/types/chat.types'",
      options: { web: ['/project/web'], backend: ['/project/api'], aliases: { '@backend': '/project/api' } },
      errors: ['boundary'],
    },
    {
      name: 'shared package roots accept the string form',
      filename: '/project/packages/logger/index.ts',
      code: "import { chat } from '@app/web/internal'",
      options: { packages: '/project/packages', appPackages: ['@app/web'] },
      errors: ['boundary'],
    },
    {
      name: 'shared package roots accept the array form',
      filename: '/project/packages/logger/index.ts',
      code: "import { chat } from '../../web/chat'",
      options: { web: ['/project/web'], packages: ['/project/packages'] },
      errors: ['boundary'],
    },
    {
      name: 'service dependencies are injected instead of reading the registry',
      filename: '/project/web/services/chat/chat.service.ts',
      code: "import { services } from '../service'",
      options: { web: ['/project/web'] },
      errors: ['boundary'],
    },
    {
      name: 'domain contracts cannot runtime-import services',
      filename: '/project/web/types/chat.types.ts',
      code: "import { chat } from '../services/chat/chat.service'",
      options: { web: ['/project/web'] },
      errors: ['boundary'],
    },
    { name: 'client services reject default UI packages', filename: 'chat.client.ts', code: "import { useState } from 'react'", errors: ['boundary'] },
    {
      name: 'client services respect custom UI packages',
      filename: 'chat.client.ts',
      code: "import { useSignal } from 'ui'",
      options: { uiPackages: ['ui'] },
      errors: ['boundary'],
    },
    {
      name: 'custom private roles cannot cross domains',
      filename: '/project/web/services/chat/chat.service.ts',
      code: "import { prompt } from '../user/user.prompts'",
      options: { web: ['/project/web'], roles: ['prompts'] },
      errors: ['boundary'],
    },
    {
      name: 'public surfaces cannot re-export their private internals',
      filename: '/project/web/services/chat/chat.service.ts',
      code: "export { normalize } from './chat-driver.normalize'",
      options: { web: ['/project/web'], roles: ['driver'] },
      errors: ['boundary'],
    },
    {
      name: 'portable library cannot import application services',
      filename: '/project/web/lib/fade.ts',
      code: "import { fade } from '@/lib/../services/fade/fade.utils'",
      options: { web: ['/project/web'], portable: true },
      errors: ['boundary'],
    },
    {
      name: 'portable library cannot import another contract',
      filename: '/project/web/lib/fade.ts',
      code: "import type { Chat } from '../types/chat.types'",
      options: { web: ['/project/web'], portable: true },
      errors: ['boundary'],
    },
    {
      name: 'portable library cannot re-export its own contract',
      filename: '/project/web/lib/fade.ts',
      code: "export type { FadeOptions } from '../types/fade.types'",
      options: { web: ['/project/web'], portable: true },
      errors: ['boundary'],
    },
    {
      name: 'local exports do not hide contract re-exports',
      filename: '/project/web/lib/fade.ts',
      code: "import type { FadeOptions } from '../types/fade.types'; export type { FadeOptions }",
      options: { web: ['/project/web'], portable: true },
      errors: ['boundary'],
    },
    {
      name: 'star exports are checked',
      filename: '/project/web/chat.ts',
      code: "export * from '@app/server/internal'",
      options: { web: ['/project/web'], backendPackages: ['@app/server'] },
      errors: ['boundary'],
    },
    {
      name: 'literal dynamic imports are checked',
      filename: '/project/web/chat.ts',
      code: "import('@app/server/internal')",
      options: { web: ['/project/web'], backendPackages: ['@app/server'] },
      errors: ['boundary'],
    },
    {
      name: 'portable import types cannot borrow another contract',
      filename: '/project/web/lib/fade.ts',
      code: "type Options = import('../types/chat.types').ChatOptions",
      options: { web: ['/project/web'], portable: true },
      errors: ['boundary'],
    },
  ])('$name', (row) => testerRun(boundariesImports, row))
})
